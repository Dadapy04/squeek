const ALL = [
  HAMSTER, HAMSTER_STEP, HAMSTER_DODGE, BITER, BITER_BITE, SPITTER, SPITTER_AIM,
  CHEST_SCRAP, CHEST_GEAR, CHEST_CORE, FLOOR_WOOD, FLOOR_DIRT, FLOOR_METAL,
  WALL_TIMBER, WALL_ROCK, WALL_MACHINE, LAMP, RAIL, PIPE,
]

export function spriteProblems(): string[] {
  const problems: string[] = []
  for (const sprite of ALL) {
    if (sprite.length !== 16) problems.push(`height ${sprite.length}`)
    for (const row of sprite) {
      if (row.length !== 16) problems.push(row)
      for (const ch of row) {
        if (ch !== '.' && !PALETTE[ch]) problems.push(`palette ${ch}`)
      }
    }
  }
  return problems
}
