export type MsgKey = keyof typeof DICT

let locale: Locale = readInitial()
const listeners = new Set<() => void>()

function readInitial(): Locale {
  try {
    const saved = globalThis.localStorage?.getItem(KEY)
    if (saved === 'id' || saved === 'en') return saved
  } catch { /* private mode */ }
  const nav = typeof navigator !== 'undefined' ? (navigator.language || '') : ''
  return nav.toLowerCase().startsWith('id') ? 'id' : 'en'
}

export function currentLocale(): Locale {
  return locale
}

export function setLocale(next: Locale): void {
  if (next !== 'id' && next !== 'en') return
  locale = next
  try { globalThis.localStorage?.setItem(KEY, next) } catch { /* ignore */ }
  if (typeof document !== 'undefined') document.documentElement.lang = next
  for (const fn of listeners) fn()
}

export function onLocale(fn: () => void): () => void {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  const row = DICT[key]
  const raw = row[locale] || row.en
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

export function dictionaryKeys(): MsgKey[] {
  return Object.keys(DICT) as MsgKey[]
}
